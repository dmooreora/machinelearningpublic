SELECT model, CASE WHEN mpg >= 25 THEN 'efficient' WHEN mpg >= 20 THEN 'moderate' ELSE 'inefficient' END AS efficiency FROM mtcars;
SELECT AVG(hp) OVER (PARTITION BY cyl) AS avg_hp_by_cyl, model, hp FROM mtcars ORDER BY cyl;
